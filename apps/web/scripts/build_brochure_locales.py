def replace_one(html: str, old: str, new: str, locale: str, key: str) -> str:
    count = html.count(old)
    if count != 1:
        raise ValueError(f"{locale}: {key}: expected one source occurrence, found {count}")
    return html.replace(old, new, 1)

def build(locale: str, copy: dict[str, str | tuple[str, str, str]], english: str) -> str:
    html = english
    for key, old in SOURCE.items():
        html = replace_one(html, old, str(copy[key]), locale, key)
    target = f"brochure-{locale}.html"
    html = replace_one(html, '<html lang="en">', f'<html lang="{copy["html_lang"]}">', locale, "html_lang")
    html = replace_one(html, 'href="https://clarvia.org/brochure.html"', f'href="https://clarvia.org/{target}"', locale, "canonical")
    html = html.replace('href="/ask"', f'href="/ask?lang={copy["ask_lang"]}"')
    if html.count(f'href="/ask?lang={copy["ask_lang"]}"') != 3:
        raise ValueError(f"{locale}: expected three Ask links")
    html = replace_one(html, 'href="/en" aria-label=', f'href="/{copy["site_lang"]}" aria-label=', locale, "home_href")
    html = replace_one(html, 'href="/en/about"', f'href="/{copy["site_lang"]}/about"', locale, "about_href")
    html = replace_one(html, 'href="/en/partners"', f'href="/{copy["site_lang"]}/partners"', locale, "partners_href")
    html = replace_one(html, 'href="/en/for-institutions"', f'href="/{copy["site_lang"]}/for-institutions"', locale, "institution_href")
    # Display the real destination. Portuguese organisation resources remain in English.
    language_note = ' (em inglês)' if locale == 'pt' else ''
    html = replace_one(html, 'clarvia.org/en/partners →', f'clarvia.org/{copy["site_lang"]}/partners{language_note} →', locale, "partners_link_text")
    html = replace_one(html, 'clarvia.org/en/for-institutions →', f'clarvia.org/{copy["site_lang"]}/for-institutions{language_note} →', locale, "institution_link_text")
    page_word, of_word, go_to = copy["words"]
    html = replace_one(html, 'data-page-word="Page" data-of-word="of" data-go-to="Go to page"', f'data-page-word="{page_word}" data-of-word="{of_word}" data-go-to="{go_to}"', locale, "body_labels")
    html = replace_one(html, '>Page 1 of 6</span>', f'>{page_word} 1 {of_word} 6</span>', locale, "initial_status")
    return html

def main() -> None:
    english = ENGLISH.read_text(encoding="utf-8")
    assert set(SOURCE) == set(COPY["fr"]) - {"words", "site_lang", "ask_lang", "html_lang"}
    for locale, copy in COPY.items():
        if set(copy) - {"words", "site_lang", "ask_lang", "html_lang"} != set(SOURCE):
            raise ValueError(f"{locale}: missing or extra translation keys")
        output = PUBLIC / f"brochure-{locale}.html"
        output.write_text(build(locale, copy, english), encoding="utf-8")
        print(output.relative_to(PUBLIC.parent))

if __name__ == "__main__":
    main()
